// Bakes the Meadow's far-plant pictures: every species in every growth band at its three angles, drawn the way the
// Meadow camera sees it (components/meadow/lod/atlasBake.ts), into two small WebP atlases in public/meadow/ (colour
// with coverage, and normals with the night glow), and writes their measurements to
// components/meadow/lod/atlasManifest.ts. Rerun it whenever the plants' look changes (lib/plant/species, the pose or
// the light plants' colours):
//
//   node scripts/bake-meadow-plants.mjs
//
// No database, no network, no secrets. Uses sharp (already installed with Next) to encode the WebP.
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ensureTypeScript, importProject } from "./lib/load-sim.mjs";

ensureTypeScript();

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const { bakeAtlas, atlasVersion, CELL_W, CELL_H } = await importProject("components/meadow/lod/atlasBake.ts");
const { BAKE_ELEVATION } = await importProject("components/meadow/lod/bands.ts");
const { default: sharp } = await import("sharp");

const started = performance.now();
const atlas = bakeAtlas();
const version = atlasVersion(atlas);
const raw = (channels) => ({ raw: { width: atlas.width, height: atlas.height, channels } });
// colour: lossy, with exact alpha and the colour kept under clear pixels. Normals and glow: full size and
// near-lossless, never lossy: lossy WebP halves its colour channels' resolution (4:2:0), which smooths the normals
// toward the camera and brightens the pictures against their light plants (atlas.test.ts holds them together)
const albedo = await sharp(Buffer.from(atlas.albedo), raw(4)).webp({ quality: 90, alphaQuality: 100, exact: true, effort: 6, smartSubsample: true }).toBuffer();
const normal = await sharp(Buffer.from(atlas.normal), raw(3)).webp({ nearLossless: true, quality: 40, effort: 6 }).toBuffer();

mkdirSync(`${ROOT}public/meadow`, { recursive: true });
writeFileSync(`${ROOT}public/meadow/plant-atlas.webp`, albedo);
writeFileSync(`${ROOT}public/meadow/plant-atlas-normal.webp`, normal);

const cells = atlas.cells.map((c) => `  [${[c.u0, c.v0, c.du, c.dv, c.width, c.height, c.footU, c.footV, c.bendV].join(", ")}],`).join("\n");
const manifest = `// Generated by scripts/bake-meadow-plants.mjs from components/meadow/lod/atlasBake.ts: do not edit by hand.
import type { Band } from "@/components/meadow/lod/bands";
import type { SpeciesId } from "@/lib/plant/species";

export const ATLAS = {
  version: "${version}",
  albedo: "/meadow/plant-atlas.webp?v=${version}",
  normal: "/meadow/plant-atlas-normal.webp?v=${version}",
  width: ${atlas.width},
  height: ${atlas.height},
  cellW: ${CELL_W},
  cellH: ${CELL_H},
  /** the elevation the pictures were taken from, radians */
  elevation: ${BAKE_ELEVATION},
} as const;

/**
 * Per cell (bands.ts cellIndex): u0, v0, du, dv (uv rect, v from the bottom), card width and height (m), foot u, v and
 * where the flower begins, v (0..1).
 */
export const CELLS: ReadonlyArray<readonly [number, number, number, number, number, number, number, number, number]> = [
${cells}
];

/** Each light plant's height from the soil, garden metres (before PLANT_SCALE). */
export const HEIGHTS: Record<SpeciesId, Record<Band, number>> = ${JSON.stringify(atlas.heights)};

/** Each light plant's triangles. */
export const TRIANGLES: Record<SpeciesId, Record<Band, number>> = ${JSON.stringify(atlas.triangles)};
`;
writeFileSync(`${ROOT}components/meadow/lod/atlasManifest.ts`, manifest);

const kb = (b) => `${(b.length / 1024).toFixed(0)} KB`;
console.log(`Meadow plant atlas ${atlas.width}x${atlas.height}, ${atlas.cells.length} cells, v${version}`);
console.log(`  public/meadow/plant-atlas.webp         ${kb(albedo)}`);
console.log(`  public/meadow/plant-atlas-normal.webp  ${kb(normal)}`);
console.log(`  components/meadow/lod/atlasManifest.ts`);
console.log(`  ${((performance.now() - started) / 1000).toFixed(1)} s`);
